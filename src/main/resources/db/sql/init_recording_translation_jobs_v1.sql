-- Recording job authority v1. Additive, no legacy data or recording binaries changed.
-- Local Hibernate update may create the same tables. Do not auto-enable Liquibase
-- against an existing database: baseline the wider schema before enabling it.
CREATE TABLE IF NOT EXISTS recording_translation_jobs (
  id VARCHAR(36) NOT NULL,
  recording_id VARCHAR(36) NOT NULL,
  runtime_session_id VARCHAR(36) NOT NULL,
  run_id VARCHAR(36) NOT NULL,
  recording_epoch BIGINT NOT NULL DEFAULT 1,
  requested_by_user_id BIGINT NOT NULL,
  idempotency_hash VARCHAR(64) NOT NULL,
  request_hash VARCHAR(64) NOT NULL,
  active_slot VARCHAR(36) NULL,
  status VARCHAR(24) NOT NULL,
  stage VARCHAR(16) NOT NULL,
  progress_percent INT NOT NULL DEFAULT 0,
  attempt INT NOT NULL DEFAULT 0,
  max_attempts INT NOT NULL,
  attempt_id VARCHAR(36) NULL,
  worker_id VARCHAR(128) NULL,
  claim_request_id VARCHAR(128) NULL,
  fencing_token BIGINT NOT NULL DEFAULT 0,
  lease_until TIMESTAMP(6) NULL,
  progress_sequence BIGINT NOT NULL DEFAULT 0,
  progress_hash VARCHAR(64) NULL,
  retry_at TIMESTAMP(6) NULL,
  error_code VARCHAR(64) NULL,
  failure_hash VARCHAR(64) NULL,
  source_bucket VARCHAR(63) NOT NULL,
  source_object_key VARCHAR(1024) NOT NULL,
  source_size_bytes BIGINT NOT NULL,
  source_sha256 VARCHAR(64) NULL,
  profile_id VARCHAR(128) NOT NULL,
  profile_version INT NOT NULL,
  settings_sha256 VARCHAR(64) NOT NULL,
  model_manifest_sha256 VARCHAR(64) NOT NULL,
  course_context_json TEXT NULL,
  checkpoint_key VARCHAR(1024) NULL,
  checkpoint_sha256 VARCHAR(64) NULL,
  checkpoint_sample BIGINT NOT NULL DEFAULT 0,
  row_version BIGINT NOT NULL DEFAULT 0,
  created_at TIMESTAMP(6) NOT NULL,
  updated_at TIMESTAMP(6) NOT NULL,
  PRIMARY KEY (id),
  CONSTRAINT uk_recording_job_idempotency UNIQUE (recording_id, requested_by_user_id, idempotency_hash),
  CONSTRAINT uk_recording_job_active_slot UNIQUE (active_slot),
  CONSTRAINT fk_recording_translation_source FOREIGN KEY (recording_id) REFERENCES meeting_recordings(id),
  INDEX idx_recording_jobs_created (recording_id, created_at),
  INDEX idx_recording_jobs_recovery (status, lease_until, retry_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS recording_job_outbox (
  id VARCHAR(36) NOT NULL,
  job_id VARCHAR(36) NOT NULL,
  dispatch_version BIGINT NOT NULL,
  available_at TIMESTAMP(6) NOT NULL,
  published_at TIMESTAMP(6) NULL,
  created_at TIMESTAMP(6) NOT NULL,
  updated_at TIMESTAMP(6) NOT NULL,
  PRIMARY KEY (id),
  CONSTRAINT uk_recording_outbox_dispatch UNIQUE (job_id, dispatch_version),
  CONSTRAINT fk_recording_outbox_job FOREIGN KEY (job_id) REFERENCES recording_translation_jobs(id),
  INDEX idx_recording_outbox_pending (published_at, available_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
